"""
Модуль для обработки строк с информацией о картах и счетах.

Содержит функции:
- mask_account_card: маскирует номер карты или счета в строке.
- get_date: извлекает дату из ISO-строки и форматирует её как ДД.ММ.ГГГГ.
"""

from datetime import datetime  # noqa: F401

from src.masks import get_mask_account, get_mask_card_number


def mask_account_card(info: str) -> str:
    """
    Маскирует номер банковской карты или счета в переданной строке.

    Функция ожидает строку, содержащую тип карты/счёта и номер, разделённые пробелом.
    Если строка не содержит двух частей или вторая часть не является числом,
    возвращается исходная строка без изменений.

    Аргументы:
        info (str): Строка вида "Visa Platinum 7000792289606361" или "Счет 73654108430135874305".

    Возвращает:
        str: Строка с замаскированным номером.

    Примеры:
        >>> mask_account_card("Visa Platinum 7000792289606361")
        'Visa Platinum 7000 79** **** 6361'

        >>> mask_account_card("Счет 73654108430135874305")
        'Счет **4305'

        >>> mask_account_card("Некорректная строка")
        'Некорректная строка'
    """
    # Разделяем строку по последнему пробелу (тип может состоять из нескольких слов)
    parts = info.rsplit(" ", 1)

    # Если частей не две (нет пробела) – возвращаем исходную строку
    if len(parts) != 2:
        return info

    name, number = parts

    # Проверяем, что вторая часть состоит только из цифр (иначе преобразование в int выдаст ошибку)
    if not number.isdigit():
        return info

    # Определяем тип по началу названия (без учёта регистра)
    if name.lower().startswith("счет"):
        # Для счёта маскируем с помощью get_mask_account
        return f"{name} {get_mask_account(int(number))}"
    else:
        # Для карты маскируем с помощью get_mask_card_number
        return f"{name} {get_mask_card_number(int(number))}"


def get_date(date_string: str) -> str:
    """
    Преобразует строку с датой в формате ISO в формат ДД.ММ.ГГГГ.

    Аргументы:
        date_string (str): Дата в формате ISO (например, "2024-03-11T02:26:18.671407").

    Возвращает:
        str: Дата в формате "ДД.ММ.ГГГГ".

    Примеры:
        >>> get_date("2024-03-11T02:26:18.671407")
        '11.03.2024'

        >>> get_date("2025-12-31T23:59:59")
        '31.12.2025'

        >>> get_date("2000-01-01")
        '01.01.2000'
    """
    # Извлекаем часть до символа 'T', если он есть, или используем всю строку
    date_part = date_string.split("T")[0]
    # Разделяем по дефисам на год, месяц, день
    year, month, day = date_part.split("-")
    # Возвращаем в порядке день.месяц.год
    return f"{day}.{month}.{year}"
